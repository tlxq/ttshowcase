/**
 * /next is where the new site is built before it goes live: a secret link, never a public page.
 * `/next?key=<key>` once per device sets a cookie and drops the key from the address; after that the cookie lets
 * the device in. Without it, /next is the site's normal 404. The key comes from PREVIEW_KEY (Vercel env, and on
 * the PCs from Proton Pass through ttpass); it is never in the repo. tools/serve.py does the same for local builds.
 *
 * Vercel runs this file as Routing Middleware in front of the static site; `next dev` runs it as its proxy. It has
 * no imports on purpose: Vercel loads it as plain Node ESM (needs ".js" paths), Next's dev server can't resolve those.
 *
 * It also sends every page's Content-Security-Policy. The build (tools/csp/manifest.mjs) hashes each page's inline
 * scripts into csp-manifest.generated.js, a module this file imports, so the header names them and the site needs no
 * 'unsafe-inline'. It is code, not a public file: no address lists /next, /admin or /wall (audit N-42). No manifest
 * (a dev server, a test): the strictest policy (no inline scripts), never a loose one.
 * Tests: src/release/middleware.test.ts.
 */
export const COOKIE = "next_key";
const YEAR = 60 * 60 * 24 * 365;

export type Gate =
  | { kind: "pass" }
  | { kind: "not-found" }
  | { kind: "redirect"; location: string; setCookie: string };

/**
 * The path as Vercel's file server sees it: decoded and normalised until it stops changing. Vercel matches
 * middleware against the raw address but serves files by the decoded one, so /%6Eext would reach next.html.
 */
export function cleanPath(pathname: string): string {
  let path = pathname;
  for (let i = 0; i < 5; i++) {
    let decoded: string;
    try {
      decoded = decodeURIComponent(path);
    } catch {
      return path;
    }
    const next = new URL(decoded.replace(/[?#]/g, encodeURIComponent), "https://x").pathname;
    if (next === path) return path;
    path = next;
  }
  return path;
}

export function isNextPath(pathname: string): boolean {
  const path = cleanPath(pathname);
  // the export also writes next.html and next.txt (the page data) beside the next/ folder
  return path === "/next" || path.startsWith("/next/") || path.startsWith("/next.");
}

/** Compares in the same time whatever the guess, so the key can't be found one letter at a time. */
export function sameKey(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
}

export function cookieValue(header: string | null, name: string): string | null {
  for (const part of (header ?? "").split(";")) {
    const i = part.indexOf("=");
    if (i > 0 && part.slice(0, i).trim() === name) {
      try {
        return decodeURIComponent(part.slice(i + 1).trim());
      } catch {
        return null; // a broken cookie is no cookie: the normal 404, never a 500
      }
    }
  }
  return null;
}

/** What to do with a request. No key set (PREVIEW_KEY empty) means /next is closed to everyone. */
export function gate(url: URL, cookieHeader: string | null, key: string | undefined): Gate {
  if (!isNextPath(url.pathname)) return { kind: "pass" };
  if (!key) return { kind: "not-found" };
  const given = url.searchParams.get("key");
  if (given !== null) {
    if (!sameKey(given, key)) return { kind: "not-found" };
    const clean = new URL(url);
    clean.searchParams.delete("key");
    const secure = url.protocol === "https:" ? "; Secure" : "";
    return {
      kind: "redirect",
      location: clean.pathname + clean.search,
      setCookie: `${COOKIE}=${encodeURIComponent(key)}; Path=/next; Max-Age=${YEAR}; HttpOnly; SameSite=Lax${secure}`,
    };
  }
  const cookie = cookieValue(cookieHeader, COOKIE);
  return cookie !== null && sameKey(cookie, key) ? { kind: "pass" } : { kind: "not-found" };
}

export type Manifest = Record<string, string>;

/** Used when the manifest can't be read: nothing inline runs, nothing is framed. */
export const STRICT_CSP =
  "default-src 'self'; script-src 'self'; object-src 'none'; base-uri 'self'; form-action 'self'; frame-ancestors 'none'";

/** The policy for an address: its page's own, or the 404 page's ("default") when it has no page. */
export function policyFor(pathname: string, manifest: Manifest | null): string {
  if (!manifest) return STRICT_CSP;
  const path = cleanPath(pathname);
  const key = path.length > 1 ? path.replace(/\/+$/, "") : path;
  const own = Object.hasOwn(manifest, key) && key !== "default" ? manifest[key] : undefined;
  return own ?? manifest.default ?? STRICT_CSP;
}

let manifestOnce: Promise<Manifest | null> | undefined;

/** The manifest built into this deployment (a deployment never changes, so it is read once). */
function loadManifest(): Promise<Manifest | null> {
  manifestOnce ??= (async () => {
    try {
      // @ts-expect-error: generated by the build (tools/csp/manifest.mjs), not in git, so the type check may not see it
      const m = (await import("./csp-manifest.generated.js")) as { default: Manifest | null };
      return m.default;
    } catch {
      return null;
    }
  })();
  return manifestOnce;
}

// Every request but plain assets: an encoded address (/%6Eext) can't be listed here, so the gate decodes it itself.
export const config = {
  matcher: [
    "/((?!_next/static/|.*\\.(?:js|css|png|jpe?g|webp|avif|gif|svg|ico|woff2?|mp4|webm|json|xml|webmanifest)$).*)",
  ],
};

export default async function middleware(request: Request): Promise<Response | undefined> {
  const url = new URL(request.url);
  const g = gate(url, request.headers.get("cookie"), process.env.PREVIEW_KEY);
  // the visitor's own cookies and bypass header go along, so a protected Vercel preview answers too
  const pass = new Headers();
  for (const h of ["cookie", "x-vercel-protection-bypass"]) {
    const v = request.headers.get(h);
    if (v) pass.set(h, v);
  }
  if (g.kind === "pass") {
    if (process.env.NODE_ENV === "development") return undefined; // `next dev` has no build, no manifest
    // "go on to the file", with the page's policy added to what comes back
    const csp = policyFor(url.pathname, await loadManifest());
    return new Response(null, {
      headers: { "x-middleware-next": "1", "Content-Security-Policy": csp },
    });
  }
  if (g.kind === "redirect") {
    return new Response(null, {
      status: 303,
      headers: {
        Location: new URL(g.location, url).toString(),
        "Set-Cookie": g.setCookie,
        "Cache-Control": "no-store",
      },
    });
  }
  // the site's own 404 page, with a 404 status and its own policy
  const csp = policyFor("/404", await loadManifest());
  const html = {
    "Content-Type": "text/html; charset=utf-8",
    "Cache-Control": "no-store",
    "Content-Security-Policy": csp,
  };
  try {
    const page = await fetch(new URL("/404", url), {
      headers: pass,
      signal: AbortSignal.timeout(3000),
    });
    if (page.ok || page.status === 404)
      return new Response(page.body, { status: 404, headers: html });
  } catch {
    // the page didn't load: a plain 404 below
  }
  return new Response("<!doctype html><title>Page not found</title><p>Page not found.</p>", {
    status: 404,
    headers: html,
  });
}
